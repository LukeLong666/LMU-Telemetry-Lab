    public String generate(Path database) {
        String carClass;
        JsonNode setup;
        try (Connection connection = connections.open(database)) {
            Map<String, String> metadata = metadataReader.read(connection);
            carClass = metadata.getOrDefault("CarClass", "Unknown Class");
            String raw = metadata.get("CarSetup");
            if (raw == null || raw.isBlank()) {
                throw new ApiException(HttpStatus.NOT_FOUND, "CarSetup metadata not found.");
            }
            setup = mapper.readTree(raw);
        } catch (ApiException e) {
            throw e;
        } catch (Exception e) {
            throw new ApiException(HttpStatus.INTERNAL_SERVER_ERROR, "Failed to read CarSetup", e);
        }

        StringBuilder output = new StringBuilder();
        output.append("VehicleClassSetting=\"").append(carClass).append("\"\n");
        output.append("UpgradeSetting=(0,0,0,0)\n");
        output.append("// Generated by LMU Telemetry Lab\n");
        output.append("//Note: settings commented out if using the default\n\n");

        for (Map.Entry<String, List<String[]>> section : mapping().entrySet()) {
            output.append('[').append(section.getKey()).append("]\n");
            for (String[] entry : section.getValue()) {
                String svmKey = entry[0];
                String source = entry[1];
                if (source.contains("//") || source.equals("\"\"") || source.equals("1") || source.equals("0.500000")) {
                    output.append(svmKey).append('=').append(source).append('\n');
                    continue;
                }
                JsonNode node = setup.path(source);
                if (node.isObject() && node.path("available").asBoolean(false)) {
                    String valueText = node.has("value") && !node.get("value").isNull()
                            ? node.get("value").toString()
                            : "0";
                    String stringValue = node.path("stringValue").asText("N/A");
                    output.append(svmKey).append('=').append(valueText).append("//").append(stringValue).append('\n');
                } else {
                    output.append(svmKey).append("=0//N/A\n");
                }
            }
            output.append('\n');
        }
        return output.toString().strip() + "\n";
    }

