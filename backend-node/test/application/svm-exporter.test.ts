async function apiError(run: () => Promise<unknown>): Promise<ApiException> {
  try {
    await run();
  } catch (error) {
    expect(error).toBeInstanceOf(ApiException);
    return error as ApiException;
  }
  throw new Error('expected an ApiException');
}

/** `key -> value` map of one `[SECTION]` block, so repeated keys stay unambiguous. */
function section(svm: string, name: string): Map<string, string> {
  const marker = `[${name}]\n`;
  const start = svm.indexOf(marker);
  expect(start, `section ${name} missing`).toBeGreaterThanOrEqual(0);
  const rest = svm.slice(start + marker.length);
  const next = rest.indexOf('\n[');
  const lines = (next < 0 ? rest : rest.slice(0, next)).split('\n');
  const entries = new Map<string, string>();
  for (const line of lines) {
    const separator = line.indexOf('=');
    if (separator > 0) entries.set(line.slice(0, separator), line.slice(separator + 1));
  }
  return entries;
}

