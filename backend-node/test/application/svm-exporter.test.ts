describe('Java number formatting helpers', () => {
  it('javaDoubleToString follows Double.toString', () => {
    // plain band [10^-3, 10^7): at least one fraction digit, no exponent
    expect(javaDoubleToString(1)).toBe('1.0');
    expect(javaDoubleToString(100)).toBe('100.0');
    expect(javaDoubleToString(45000)).toBe('45000.0');
    expect(javaDoubleToString(9999999)).toBe('9999999.0');
    expect(javaDoubleToString(0.5)).toBe('0.5');
    expect(javaDoubleToString(2.665)).toBe('2.665');
    expect(javaDoubleToString(2.675)).toBe('2.675');
    expect(javaDoubleToString(-3.75)).toBe('-3.75');
    expect(javaDoubleToString(0.001)).toBe('0.001');
    expect(javaDoubleToString(0.01)).toBe('0.01');
    expect(javaDoubleToString(0.1)).toBe('0.1');
    expect(javaDoubleToString(0.03)).toBe('0.03');
    expect(javaDoubleToString(1.0000001)).toBe('1.0000001');
    expect(javaDoubleToString(0)).toBe('0.0');
    expect(javaDoubleToString(-0)).toBe('-0.0');
    // outside the plain band Java emits d.dddEnotation, trailing zeros dropped
    expect(javaDoubleToString(10000000)).toBe('1.0E7');
    expect(javaDoubleToString(123456780)).toBe('1.2345678E8');
    expect(javaDoubleToString(1.7976931348623157e308)).toBe('1.7976931348623157E308');
    expect(javaDoubleToString(1e21)).toBe('1.0E21');
    expect(javaDoubleToString(0.0001)).toBe('1.0E-4');
    expect(javaDoubleToString(0.0009999)).toBe('9.999E-4');
    // not-a-number and infinities keep Java's spelling; JSON.stringify would say null
    expect(javaDoubleToString(Number.NaN)).toBe('NaN');
    expect(javaDoubleToString(Number.POSITIVE_INFINITY)).toBe('Infinity');
    expect(javaDoubleToString(Number.NEGATIVE_INFINITY)).toBe('-Infinity');
  });

  it('javaIsBlank and javaStrip use Character.isWhitespace, not JS \\s', () => {
    expect(javaIsBlank('')).toBe(true);
    expect(javaIsBlank(' \t\n\u001c')).toBe(true); // 0x1C..0x1F are whitespace in Java
    expect(javaIsBlank('\u00a0')).toBe(false); // NBSP is not, unlike JS \s
    expect(javaIsBlank('\u202f')).toBe(false);
    expect(javaIsBlank('x')).toBe(false);
    expect(javaStrip('\u00a0x\u00a0')).toBe('\u00a0x\u00a0');
    expect(javaStrip('\n\nx\n\n')).toBe('x');
  });

  it('parseCarSetup keeps number literals the way Jackson types them', () => {
    const tree = parseCarSetup(
      '{"i":1,"d":1.0,"e":1e2,"big":9007199254740993,"neg":true,"nul":null}',
    );
    expect(tree.kind).toBe('object');
    const show = (key: string): string => {
      expect(tree.kind).toBe('object');
      const node = tree.kind === 'object' ? tree.props.get(key) : undefined;
      return JSON.stringify(node);
    };
    expect(show('i')).toBe('{"kind":"number","raw":"1","value":1,"integral":true}');
    expect(show('d')).toBe('{"kind":"number","raw":"1.0","value":1,"integral":false}');
    expect(show('e')).toBe('{"kind":"number","raw":"1e2","value":100,"integral":false}');
    expect(show('big')).toBe(
      '{"kind":"number","raw":"9007199254740993","value":9007199254740992,"integral":true}',
    );
    expect(show('neg')).toBe('{"kind":"boolean","value":true}');
    expect(show('nul')).toBe('{"kind":"null"}');
  });

  it('rejects the JSON Jackson rejects', () => {
    expect(() => parseCarSetup('{"v":NaN}')).toThrow(SyntaxError);
    expect(() => parseCarSetup('{"v":Infinity}')).toThrow(SyntaxError);
    expect(() => parseCarSetup("{'v':1}")).toThrow(SyntaxError);
    expect(() => parseCarSetup('{"v":1,}')).toThrow(SyntaxError);
    expect(() => parseCarSetup('{"v"1}')).toThrow(SyntaxError);
  });
});

